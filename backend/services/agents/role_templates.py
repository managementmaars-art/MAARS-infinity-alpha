def detect_role_template(agent_row: dict) -> dict | None:
    """Return the role-family template matching this agent, or None if
    no role-family matches (caller then falls back to dept template).

    Match blob: role + name + description + capabilities. Lower-cased,
    substring match. First matching template wins — order in
    ROLE_TEMPLATES is the priority.
    """
    role = (agent_row.get("role") or "").lower()
    name = (agent_row.get("name") or "").lower()
    desc = (agent_row.get("description") or "").lower()
    caps = " ".join(str(c) for c in (agent_row.get("capabilities") or [])).lower()
    blob = f" {role}  {name}  {desc}  {caps} "
    for tpl in ROLE_TEMPLATES:
        for token in tpl["match_any"]:
            if token.lower() in blob:
                return tpl
    return None


