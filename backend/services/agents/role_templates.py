"""Role-family SOP templates — the third layer of agent training.

Layer 1: per-agent persona (system_prompt + capabilities) — automatic,
         threaded into every SOP step by run_sop().
Layer 2: THIS FILE — role-family SOPs. A Graphic Designer follows a
         DIFFERENT workflow than a Copywriter even though both sit in
         Creative & Marketing. Role-family SOPs are hand-authored for
         the top role clusters so the SOP steps match the actual craft.
Layer 3: department template fallback (office_templates.py) for the
         long tail of rare/one-off roles.

Each role template exposes the same shape department templates do, so
materialize_office() can consume either.

Role detection uses keyword matching against agent.role + agent.name +
agent.description. First matching family wins; order matters — more
specific detectors come first in ROLE_TEMPLATES.
"""
from __future__ import annotations
from .agent_office import SOPStep, SkillWorkflow, QualityRule


